/**
 * Navigation section component for sidebar menu items
 */

'use client';

interface NavigationItem {
  id: string;
  label: string;
  icon: React.ReactNode;
  isActive?: boolean;
  onClick: () => void;
}

interface NavigationSectionProps {
  items: NavigationItem[];
}

export function NavigationSection({ items }: NavigationSectionProps) {
  return (
    <nav className="px-3 py-2 border-b border-navy-700">
      <ul className="space-y-1">
        {items.map((item) => (
          <li key={item.id}>
            <button
              onClick={item.onClick}
              className={`w-full flex items-center gap-3 px-4 py-3 rounded-lg transition-all duration-200 ease-in-out ${
                item.isActive
                  ? 'bg-blue-accent/10 text-blue-accent border border-blue-accent/30'
                  : 'text-text-secondary hover:text-text-primary hover:bg-navy-800/50 border border-transparent'
              }`}
              aria-current={item.isActive ? 'page' : undefined}
              aria-label={`Navigate to ${item.label}`}
            >
              <span className="w-5 h-5 flex-shrink-0">{item.icon}</span>
              <span className="text-sm font-semibold">{item.label}</span>
            </button>
          </li>
        ))}
      </ul>
    </nav>
  );
}

